#!/usr/bin/env node
/**
 * Generates packages/core/src/analytics/story-wordlist.ts: a ~50k-word English
 * list for the typo fingerprint on machines without /usr/share/dict/words.
 *
 * Words come from Webster's Second International (public domain; shipped as
 * /usr/share/dict/web2 on macOS/BSD). They are ranked by how often they occur
 * in locally installed, openly licensed technical English: the README/.d.ts
 * docs under node_modules, the system man pages and Python's standard library.
 * The output holds only words, never any corpus text.
 *
 *   node scripts/make-wordlist.mjs [--limit 50000]
 */
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import zlib from 'node:zlib';
import {createHash} from 'node:crypto';

const limit = Number(process.argv[process.argv.indexOf('--limit') + 1]) || 50000;
const web2 = new Set(fs.readFileSync('/usr/share/dict/web2', 'utf8').split('\n').filter(w => /^[a-z]{2,15}$/.test(w)));
const freq = new Map();
const count = text => { for (const m of text.replace(/([a-z])([A-Z])/g, '$1 $2').toLowerCase().matchAll(/[a-z]{2,15}/g)) freq.set(m[0], (freq.get(m[0]) ?? 0) + 1); };
function walk(dir, accept) {
  let entries;
  try { entries = fs.readdirSync(dir, {withFileTypes: true}); } catch { return; }
  for (const e of entries) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, accept);
    else if (accept(e.name)) { try { const b = fs.readFileSync(p); count((e.name.endsWith('.gz') ? zlib.gunzipSync(b) : b).toString('utf8')); } catch { /* skip */ } }
  }
}
walk(path.resolve('node_modules/.pnpm'), n => /\.(md|markdown|txt)$|\.d\.ts$/i.test(n));
walk('/usr/share/man', n => /\.\d\w*(\.gz)?$/.test(n));
const py = process.env.PYTHON_LIB_ROOT ?? '/opt/homebrew/opt/python@3.14/Frameworks/Python.framework/Versions/3.14/lib';
for (const root of ['/opt/homebrew/lib', '/usr/lib', py]) for (const v of (fs.existsSync(root) ? fs.readdirSync(root) : []).filter(n => /^python3\.\d+$/.test(n)).slice(0, 1)) walk(path.join(root, v), n => n.endsWith('.py'));

// Never ship a word the repository's privacy check fingerprints as private subject matter.
const fingerprints = [...fs.readFileSync(path.resolve('scripts/check-privacy.py'), 'utf8').matchAll(/\((\d+), (\d+), '([0-9a-f]{64})'\)/g)]
  .map(m => ({width: Number(m[1]), prefix: Buffer.from(Number(m[2]).toString(16).padStart(6, '0'), 'hex').toString(), digest: m[3]}));
const flagged = w => fingerprints.some(f => { for (let i = w.indexOf(f.prefix); i >= 0; i = w.indexOf(f.prefix, i + 1)) if (createHash('sha256').update(w.slice(i, i + f.width)).digest('hex') === f.digest) return true; return false; });
const ranked = [...web2].filter(w => freq.has(w)).sort((a, b) => freq.get(b) - freq.get(a) || (a < b ? -1 : 1));
const technical = [...freq].filter(([w, n]) => !web2.has(w) && n >= 200 && w.length >= 3).sort((a, b) => b[1] - a[1]).map(([w]) => w).slice(0, 3000);
const words = [...new Set([...ranked.slice(0, limit - technical.length), ...technical])].filter(w => !flagged(w)).sort();
const out = path.resolve('packages/core/src/analytics/story-wordlist.ts');
fs.writeFileSync(out, `/** Generated by scripts/make-wordlist.mjs (${words.length} words; Webster's 2nd, public domain, ranked by technical-English frequency). Do not edit. */\n`
  + `export const STORY_WORDLIST = ${JSON.stringify(words.join(' '))};\n`);
console.log(`${words.length} words (${ranked.length} ranked web2, ${technical.length} technical) -> ${out} ${fs.statSync(out).size} bytes`);
void os;
