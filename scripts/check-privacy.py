# (label, argv after the script name, expected exit code). These probe the
# COMMAND, not a rule.
#
# WHY. `main()` was `files = argv[1:] or tracked_files()`, so an argument that
# was not `--selftest` became a file list -- including one that started with a
# dash. `python3 scripts/check-privacy.py --list-pins` therefore swept one
# nonexistent path, found nothing in it, concluded that all fourteen pinned
# violations were "now clean -- delete the DEBT line", and exited 1 with a
# confident and entirely wrong failure. A guard whose failure output can be
# wrong is worse than no guard, because somebody will act on it: the advice it
# gave was to delete a ratchet.
#
# Each probe runs the real command in a subprocess, as a person would type it,
# rather than calling the parser underneath it (`09` rule 12).
ARG_PROBES: list[tuple[str, list[str], int]] = [
    ('an unknown flag is a usage error, not a file list', ['--list-pins'], 2),
    ('a flag-shaped argument after a real path is still a usage error',
     ['scripts/check-privacy.py', '--pins'], 2),
    ('CONTROL an explicit path list is still accepted', ['scripts/check-privacy.py'], 0),
    # The same failure one layer down: a partial sweep used to report every
    # DEBT entry it had not looked at as "now clean -- delete the DEBT line".
    # It judges only the paths it was given now. This probe is worth keeping
    # even while DEBT is empty, because it is what will catch the regression on
    # the day somebody adds a pin back.
    ('a partial sweep does not judge the pins it did not look at',
     ['scripts/check-privacy.py', 'NOTICE'], 0),
]


def _probe_rules(path: str, text: str) -> set[str]:
    """Every rule that fires on one probe's text, at one pseudo-path."""
    lines = text.split('\n')
    got = set()
    for rule, spec in RULES.items():
        if spec.get('file'):
            if spec['file'](path, lines):
                got.add(rule)
            continue
        for n, line in enumerate(lines):
            nxt = lines[n + 1] if n + 1 < len(lines) else ''
            hits = spec['find'](line, nxt) if spec.get('lookahead') else spec['find'](line)
            if hits:
                got.add(rule)
    return got


def selftest() -> int:
    bad = []
    for row in SELFTEST:
        label, text, expect = row[0], row[1], row[2]
        # Rows with no pseudo-path are checked outside docs/, which is where all
        # eleven of the original probes have always effectively lived.
        path = row[3] if len(row) > 3 else 'scripts/probe.txt'
        got = _probe_rules(path, text)
        if got != set(expect):
            bad.append(f'  {label}\n      expected {sorted(expect)}, got {sorted(got)}')
        print(f"  {'ok  ' if got == set(expect) else 'FAIL'}  {label}"
              f"{'  [' + ', '.join(sorted(got)) + ']' if got else ''}")

    for label, args, want in ARG_PROBES:
        proc = subprocess.run([sys.executable, str(Path(__file__).resolve()), *args],
                              cwd=REPO, capture_output=True, text=True)
        ok = proc.returncode == want
        if not ok:
            bad.append(f'  {label}\n      expected exit {want}, got {proc.returncode}')
        print(f"  {'ok  ' if ok else 'FAIL'}  {label}  [exit {proc.returncode}]")

    if bad:
        print('\nSELFTEST FAILED:\n' + '\n'.join(bad))
        return 1
    print(f'\n  {len(SELFTEST) + len(ARG_PROBES)} probes, all as expected.')
    return 0


USAGE = """usage: check-privacy.py [--selftest | PATH ...]

  no arguments   sweep every tracked text file (what CI runs)
  PATH ...       sweep only these paths, relative to the repo root
  --selftest     run the rule probes and the argument probes, sweep nothing

Anything else is an error. It used to be a FILE NAME: `--list-pins` was swept as
a path, found to be missing, and reported every pinned violation as "now clean
-- delete the DEBT line". Being confidently wrong is the one thing a guard may
not do."""


def parse_args(args: list[str]) -> tuple[list[str] | None, str | None]:
    """(files, error). `files == []` means sweep everything tracked.

    Kept separate from main() so the failure has one place to live, and so the
    error text is the same whether the bad flag came first or last.
    """
    if '--selftest' in args:
        if len(args) > 1:
            return None, '--selftest takes no other arguments'
        return None, None
    unknown = [a for a in args if a.startswith('-')]
    if unknown:
        return None, f"unknown option: {' '.join(unknown)}"
    return args, None


def inventory_line(inventory: dict[str, str | None], partial: bool) -> str:
    """The `corpus-id-inventory` rule's state, in one line, on every run.

    A guard that only prints "ok" teaches nobody what it looked at. This says
    how many id-shaped tokens are in the repository, which derivable source
    accounts for each of them, and how big the unexplained residue is -- which
    is the number ID_INVENTORY_PINS ratchets down."""
    if partial:
        return ('id inventory: partial sweep, not counted '
                '(run with no arguments for the repository-wide number).')
    by: dict[str, int] = {}
    for source in inventory.values():
        by[source or 'UNACCOUNTED'] = by.get(source or 'UNACCOUNTED', 0) + 1
    un = by.pop('UNACCOUNTED', 0)
    breakdown = ', '.join(f'{n} {label}' for label, n in sorted(by.items(), key=lambda x: -x[1]))
    pinned_files = len(ID_INVENTORY_PINS)
    pinned_hits = sum(c for _p, c, _w in ID_INVENTORY_PINS)
    return (f'id inventory: {len(inventory)} distinct id-shaped tokens in tracked text; '
            f'{len(inventory) - un} accounted for ({breakdown}); '
            f'{un} unaccounted (ceiling {ID_INVENTORY_CEILING}), pinned at '
            f'{pinned_hits} occurrences across {pinned_files} files.')


def unaccounted_total(inventory: dict[str, str | None]) -> int:
    """How many DISTINCT id-shaped tokens no derivable source explains.

    Gated separately from ID_INVENTORY_PINS, because those pin a COUNT per
    file and a count cannot see a substitution: swapping one unaccounted id
    for a brand-new one inside an already-pinned file leaves every per-file
    count identical, and the repository-wide figure was printed and never
    checked. Measured that way, the total went 29 -> 30 and the guard still
    exited 0.

    So the total is a ratchet too. Lower it when it falls; it may never rise.
    """
    return sum(1 for source in inventory.values() if source is None)


def main(argv: list[str]) -> int:
    files, err = parse_args(argv[1:])
    if err:
        print(f'check-privacy.py: {err}\n', file=sys.stderr)
        print(USAGE, file=sys.stderr)
        return 2
    if files is None:
        return selftest()
    # A partial sweep must not report the pins it did not look at. Same failure
    # as the unknown-flag one above, one layer down: given an explicit path
    # list, every DEBT entry for a path NOT in that list is trivially "not
    # found", and the run would advise deleting all of them. So a partial sweep
    # judges only the paths it was given.
    partial = bool(files)
    files = files or tracked_files()
    found: dict[tuple[str, str], list[tuple[int, str]]] = {}
    inventory: dict[str, str | None] = {}
    swept = 0

    for path in files:
        p = REPO / path
        if p.suffix.lower() in SKIP_SUFFIXES or not p.is_file():
            continue
        try:
            text = p.read_text(encoding='utf-8')
        except (UnicodeDecodeError, OSError):
            continue
        swept += 1
        # The inventory is repo-wide, so it is counted here rather than inside a
        # rule: every id-shaped token in every file that is read, INCLUDING the
        # ALLOWed trees, classified once. `found` still decides pass/fail; this
        # is what the run reports about itself on its last line.
        # ...except this file's own probe fixtures, which are not repository
        # content: they exist to be flagged, and counting them would put the
        # guard's test data into the number the guard reports about the repo.
        if path != 'scripts/check-privacy.py':
            for tok in id_tokens(text):
                inventory.setdefault(tok[:8], classify_id(tok))
        for rule, spec in RULES.items():
            if allowed(path, rule):
                continue
            lines = text.splitlines()
            if spec.get('file'):
                # A whole-file rule: it gets the path and every line, and hands
                # back the (line number, message) pairs itself.
                for n, hit in spec['file'](path, lines):
                    found.setdefault((path, rule), []).append((n, hit))
                continue
            for n, line in enumerate(lines, 1):
                # `find` takes the next line too when it declares a second
                # parameter, so a rule can span a wrapped comment.
                hits = (spec['find'](line, lines[n] if n < len(lines) else '')
                        if spec.get('lookahead') else spec['find'](line))
                for hit in hits:
                    found.setdefault((path, rule), []).append((n, hit))

    pinned = {(path, rule): (count, why) for path, rule, count, why in DEBT}
    pinned.update({(path, 'corpus-id-inventory'): (count, why)
                   for path, count, why in ID_INVENTORY_PINS})
    new: list[str] = []
    stale: list[str] = []

    for (path, rule), hits in sorted(found.items()):
        if (path, rule) in pinned:
            expected, _why = pinned[(path, rule)]
            if len(hits) > expected:
                new.append(
                    f'  {path}  [{rule}]  pinned at {expected}, found {len(hits)}\n'
                    + '\n'.join(f'      line {n}: {h}' for n, h in hits[expected:]))
            elif len(hits) < expected:
                stale.append(f'  {path}  [{rule}]  pinned at {expected}, found only {len(hits)}')
            continue
        shown = '\n'.join(f'      line {n}: {h}' for n, h in hits[:8])
        if len(hits) > 8:
            shown += f'\n      ... and {len(hits) - 8} more'
        new.append(f"  {path}  [{rule}]  {RULES[rule]['why']}\n{shown}")

    swept_paths = set(files)
    for (path, rule), (expected, _why) in sorted(pinned.items()):
        if partial and path not in swept_paths:
            continue
        if (path, rule) not in found:
            stale.append(f'  {path}  [{rule}]  pinned at {expected}, now clean '
                         f'-- delete the DEBT line')

    # The repository-wide ceiling, checked only on a full sweep: a partial one
    # has not looked at enough of the tree to say anything about a total.
    over_ceiling = (not partial) and unaccounted_total(inventory) > ID_INVENTORY_CEILING

    if not new and not stale and not over_ceiling:
        pins = (f'{len(DEBT)} pinned known violations all at their expected counts'
                if DEBT else 'no pinned known violations left to carry')
        noun = 'file' if swept == 1 else 'files'
        print(f'privacy: {swept} tracked text {noun} swept, no real-corpus content, {pins}.')
        print(inventory_line(inventory, partial))
        return 0

    print('=' * 78)
    print('PRIVACY CHECK FAILED -- a committed file carries real-corpus content.')
    print('=' * 78)
    if new:
        print('\nNEW VIOLATIONS:\n')
        print('\n'.join(new))
    if stale:
        print('\nPINNED COUNTS THAT NO LONGER MATCH '
              '(somebody scrubbed a file and left the pin behind):\n')
        print('\n'.join(stale))
    if over_ceiling:
        print(f'''
MORE UNACCOUNTED ID-SHAPED TOKENS THAN THE CEILING ALLOWS:

  {unaccounted_total(inventory)} distinct, ceiling {ID_INVENTORY_CEILING}.

The per-file pins are COUNTS, so they cannot see a substitution: swap one
unaccounted id for a new one inside a pinned file and every count still
matches. This total is the ratchet that does see it. Either account for the
new token -- add its source to ID_SOURCES if the repository can derive it --
or repair the file. Lower the ceiling when it falls; never raise it.''')
    print()
    print(inventory_line(inventory, partial))
    print(f"""
{'-' * 78}
THE RULE, so you can decide what to do about it
{'-' * 78}

This repo is public and its subject is other people's transcripts. A committed
file carries REAL-CORPUS CONTENT when it reproduces, or lets a reader
reconstruct, something that was inside a live AI transcript or the private
working tree that transcript ran in:

  1. transcript prose -- what a human typed, what an agent replied or reasoned,
     and the subject matter of it (a topic is prose with the words taken out);
  2. corpus identity -- a session/thread/composer uuid, or a session title;
  3. the private tree -- a home path or project slug naming a directory that is
     not this repository, and the file names inside it. The directory name IS
     the private fact: `maths_practice` says what somebody was studying.

These are NOT violations, and you should not "fix" them:

  a. this repository's own checkout path, e.g. `/Users/<you>/randomness/potsherd`
     -- it names no private work, and it is in every pasted pnpm/vitest banner,
     which is what makes the pasted run evidence;
  b. a kept `--potsherd-dir` cited as evidence -- the plans' ground rules
     REQUIRE a real-corpus run to be cited by its kept dir and its numbers. What
     must not follow it is the transcript-derived prose. Re-examinable does not
     mean published;
  c. obviously synthetic placeholders and the demo corpus's own ids --
     `/path/to/project`, `/Users/example`, `00000000-...`, and everything under
     `evals/fixture/`, `tests/fixtures/`, `docs/screens/`.

SO: replace the content, keep the structure. A record keeps every key, the same
types, the same nesting and the same ordering -- only the human-authored values
become synthetic, and they stay internally consistent so the format is still
learnable. See docs/upstream/PHASE-1-SCOUT.md for what that looks like done.

If a file genuinely needs the real shape and you cannot change it, add a line to
DEBT in scripts/check-privacy.py with an exact count and a reason. Do not widen
ALLOW to cover it: ALLOW is for trees that are synthetic by construction, DEBT is
for known violations, and the difference is the point.

No regex recognises prose. Passing this check does not mean a file is clean --
it means the file carries no leak we have already seen. Read what you commit.
""")
    return 1


if __name__ == '__main__':
    sys.exit(main(sys.argv))
