#!/usr/bin/env python3
"""
check-privacy.py -- fail when a committed file carries real-corpus content.

This repository is public. Its whole subject is other people's AI transcripts,
so the one bug it must never ship is a committed file that quotes somebody's
live corpus. `scripts/make-screens.sh` has asserted a forbidden-string list over
`docs/screens/` and the README since phase 0; this is that idea over every
tracked file, and it runs in CI.


THE RULE
========

A committed file carries REAL-CORPUS CONTENT when it reproduces -- or lets a
reader reconstruct -- something that was inside a live AI transcript, or inside
the private working tree that transcript ran in. Three families:

  1. TRANSCRIPT PROSE .. what a human typed, or what an agent replied or
     reasoned, verbatim or near-verbatim. Also the subject matter: a topic that
     appears in this repo only because it was in somebody's real sessions is
     the same leak in fewer words.

  2. CORPUS IDENTITY ... a session, thread or composer uuid that indexes a live
     transcript, and a session title.

  3. THE PRIVATE TREE .. a home-directory path or project slug naming a
     directory that is NOT this repository, plus the file names and file
     contents inside it. A project directory name is a fact about somebody's
     private life -- `maths_practice` and `Infant-State-Recognition-System`
     say what a person was studying and building -- and the slug is also the
     join key back to the transcript it came from.

And three things that look like leaks and are NOT, because scrubbing them would
cost the repo something it needs:

  a. THIS REPO'S OWN CHECKOUT PATH. `/Users/<name>/randomness/potsherd` names no
     private work. It appears because pnpm and vitest print their cwd in the
     banner of every pasted run, and the unedited banner is what makes the
     pasted evidence evidence.

  b. A KEPT `--potsherd-dir` CITED AS EVIDENCE. The plans' ground rules require
     it: "a real-corpus run is cited by its kept `--potsherd-dir` and its
     numbers". That path is mandated, not leaked. What must not follow it is the
     transcript-derived prose -- re-examinable does not mean published.

  c. OBVIOUSLY SYNTHETIC PLACEHOLDERS AND THE DEMO CORPUS'S OWN IDS.
     `/path/to/project`, `/Users/example`, `00000000-...`, and everything under
     `evals/fixture/`, `tests/fixtures/` and `docs/screens/`, which are
     generated by `scripts/make-*-corpus.mjs` from a seeded PRNG.

Severity follows from that: (1) and (2) are unconditional. (3) is a violation
even when it is "only a path", because the directory name is the private fact.


WHAT THIS SCRIPT CAN AND CANNOT CHECK
=====================================

No regex recognises prose. This guard is a floor, not a ceiling: passing it does
not mean a file is clean, it means the file carries no leak we have already
seen. When you add a real-corpus run to the repo, read what you are committing.

Rule by rule, what it catches and what it does not:

  home-path ...... catches `/Users/<user>/x` and `/home/<user>/x`, in slash and
                   Claude-Code-slug form, on any account not in
                   PLACEHOLDER_USERS. `..` is resolved before the own-tree
                   exemption is applied, so `/Users/x/randomness/../Client` no
                   longer passes as "the repo's own tree".
                   STILL OPEN: `~/x`, `$HOME/x` and a bare relative slug --
                   `Some-Client/notes.md` is a private path with no home
                   directory in front of it and nothing here will see it.
                   Windows paths (`C:` + backslashes) are not matched either.

  project-name ... an exact-substring list. Exact is the whole weakness: the
                   list held `Meghavi` and `format.ts` shipped `Second-Brain`
                   for a year, because a different substring of the same
                   private name is a different string. Adding a name catches
                   that name and teaches nothing about the next one.

  corpus-id ...... hashed, so the guard can ban an id without publishing it.
                   Catches the ids we know about, in short and uuid form.
                   CLOSED, mostly, by the rule below: for eight phases this was
                   an enumerated blocklist holding three hashes while 25 real
                   ids sat in 39 tracked files, and the note that used to be
                   here -- "an id nobody has told this file about looks exactly
                   like a synthetic one" -- was the whole of why.

  corpus-id-inventory
                   the inversion of the rule above, added in phase 8 (T8.H)
                   after the blocklist's stated limitation turned out to be a
                   25-id backlog (`plans/08` rule 13). Instead of listing what
                   is forbidden it enumerates every id-shaped token in tracked
                   text and asks which source in this repository accounts for
                   it: the generated corpus trees, the corpus generators, git's
                   own shas, `pnpm-lock.yaml`, and a measured entropy test for
                   hand-typed literals. Anything nothing accounts for is
                   reported, and the residue is ratcheted by ID_INVENTORY_PINS.
                   It cannot tell a real id from an invented one -- nothing here
                   can, and no copy of the reference corpus is or will be in
                   this repo. What it can do is refuse an UNEXPLAINED id, which
                   makes the by-hand check cheap and bounded.
                   STILL OPEN, and each of these is a live gap, not a caveat:
                   (1) an id that also appears in a source tree is accounted for
                   BY that tree, so a source that is not clean launders
                   everything it touches -- which had already happened, see
                   ID_SOURCE_EXCLUDE; (2) the entropy test at 3 distinct hex
                   digits misses 1 real id in 3,013 and, if it were raised to 4
                   to quieten `docs/`, would miss 43; (3) an eight-DIGIT decimal
                   integer is the same shape as an all-digit id and there is no
                   fix that does not create a 2.3% blind spot; (4) 30 tokens are
                   pinned rather than repaired, 19 files' worth of them because
                   phase 8's worker map reserved those files to somebody else.

  corpus-title ... hashed word n-grams, scanned across one line break so a
                   wrapped comment is still one title.
                   STILL OPEN: same as ids -- only titles already listed, and
                   only near-verbatim. Reword a title and it passes.

  corpus-topic ... a known-vocabulary list, and the same exact-substring
                   weakness as project-name. It is the only thing standing
                   between family (1) and the repository, and family (1) is
                   free-form prose. Treat it as a reminder, not a filter.

  transcript-record
                   the one shape of family (1) that a regex CAN see, added in
                   phase 8 after `docs/upstream/PHASE-1-SCOUT.md` published a
                   real `~/.pi` assistant `thinking` block for six phases and
                   every rule above passed it every time. A transcript record
                   is a one-line JSON object -- `"thinking":"`, `"role":
                   "assistant"`, `"parentId":` or `<user_query>` -- pasted into
                   `docs/**` as a format sample. When one carries a prose
                   payload over 100 characters and nothing within 60 lines
                   declares the samples synthetic, this fires.
                   It does not judge whether the prose is real; nothing here
                   can. It enforces a POLICY: say what a sample is, next to it.
                   STILL OPEN: the declaration is an assertion by whoever
                   committed the file, so typing the word walks around it. That
                   is a real limit and, per this file's own history, worth
                   having anyway -- the six-phase leak was nobody being asked
                   the question, not somebody answering it falsely. Also open:
                   a payload UNDER 100 characters is invisible, and a record
                   split across several lines by a formatter is not matched.


THE COMMAND
===========

  check-privacy.py              sweep every tracked text file. This is CI.
  check-privacy.py PATH ...     sweep only these paths.
  check-privacy.py --selftest   run the probes; sweep nothing.

Anything else exits 2 with a usage message. It used to be read as a FILE NAME:
`--list-pins` was swept as a path, found missing, and every pinned violation was
reported as "now clean -- delete the DEBT line". A guard that is confidently
wrong is worse than no guard, because its advice was to break the ratchet.


ALLOW vs DEBT
=============

ALLOW exempts a whole tree that is synthetic by construction. Every entry is
justified in place and is expected to stay forever.

DEBT pins a known violation that a specific task was not allowed to fix, by
exact count. Both directions fail: a count that GREW is a new leak, a count that
SHRANK means somebody scrubbed it and forgot to unpin it. That makes the list a
ratchet rather than a place to hide things. It ran 34 -> 14 -> 0 across phases
7 and 8 and is EMPTY as of 22 aug 2026; an empty DEBT means every violation this
script can see has been repaired, and nothing more than that.

ID_INVENTORY_PINS is a THIRD list and the `corpus-id-inventory` rule's own
ratchet, kept apart from DEBT so that DEBT reaching zero stays a fact. It was
born non-empty, at 30 tokens across 35 files, because the rule was switched on
and found a backlog -- which is what a new rule is for and is the honest number,
not a target that was negotiated down. It ratchets the same way in both
directions. Nineteen of its files are RESERVED to other workers; the rest are
four categories the rule cannot derive and each line says which.
"""

from __future__ import annotations

import hashlib
import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent

# --------------------------------------------------------------------- rules

# Home-directory paths, in both the `/Users/name/x` and the Claude Code project
# slug `-Users-name-x` form. Matched broadly, then filtered by is_private_home()
# below, because whether a home path is a leak depends on where it points.
#
# `home` as well as `Users`: a Linux machine's private tree is `/home/<user>/x`
# and its Claude Code slug is `-home-<user>-x`, and until T5.9 neither was
# matched at all. Every `/home/...` in this repo today is `dev` or `x`, both
# documented placeholders, so widening it costs nothing and closes a whole
# platform.
HOME_PATH = re.compile(r'[-/](?:Users|home)[-/][A-Za-z0-9_.]+(?:[-/][A-Za-z0-9_.]+)*')

# Names that are documented stand-ins, not accounts. `x`, `me` and `dana` are
# used by packages/core docstrings; `example` is what the scrubbed docs use.
PLACEHOLDER_USERS = {'example', 'dev', 'dana', 'someone', 'user', 'you',
                     'test', 'x', 'me', 'name'}

# First path segment under the home directory that makes a path this project's
# own rather than somebody's private work. `randomness` holds the repository,
# the plan folder beside it and the kept `--potsherd-dir` evidence corpora;
# `.potsherd` is this tool's own state directory. Citing either by name is what
# the ground rules ask for. See (a) and (b) above.
OWN_TREE_ROOTS = ('randomness', '.potsherd')


def is_private_home(token: str) -> bool:
    """True when a `/Users/...` or `-Users-...` token names somebody's private tree."""
    parts = re.split(r'[-/]', token.lstrip('-/'))
    # `..` escapes the own-tree exemption. `/Users/zebra/randomness/../Client`
    # matched OWN_TREE_ROOTS on segment 3 and was waved through, while naming a
    # sibling of the repo -- which is exactly the private tree this rule exists
    # for. Resolve the traversal first, then decide.
    resolved: list[str] = []
    for seg in parts:
        if seg == '.':
            continue
        if seg == '..':
            if resolved:
                resolved.pop()
            continue
        resolved.append(seg)
    parts = resolved
    # parts == ['Users', <account>, <first segment>, ...]
    if len(parts) < 2:
        return False
    account = parts[1]
    if account.lower() in PLACEHOLDER_USERS:
        return False
    # `/Users/zebra` with nothing after it names a home directory and no project.
    if len(parts) == 2:
        return False
    if parts[2] in OWN_TREE_ROOTS:
        return False
    # Terminal output elides long paths mid-word (`-Users-zebra-rando...`). A
    # truncated final segment that is a prefix of an own-tree root is that root.
    if len(parts) == 3 and any(r.startswith(parts[2]) for r in OWN_TREE_ROOTS):
        return False
    return True


